import { chromium, expect } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=fileURLToPath(new URL('../../',import.meta.url));
const output=path.join(root,'.tools/native-test');
const adbPath=path.join(process.env.LOCALAPPDATA,'Android/Sdk/platform-tools/adb.exe');
const adb=(...args)=>execFileSync(adbPath,['-P','5051','-s','emulator-5586',...args],{encoding:'utf8',timeout:20000});
if(!adb('emu','avd','name').split(/\r?\n/).some(line=>line.trim()==='jianjie_verify36'))throw new Error('Unknown test target');
const pid=adb('shell','pidof','dev.keepaccounts.jianjie2').trim();
if(!/^\d+$/.test(pid))throw new Error('Test app not running');
adb('forward','tcp:9238',`localabstract:webview_devtools_remote_${pid}`);
const browser=await chromium.connectOverCDP('http://127.0.0.1:9238',{noDefaults:true,artifactsDir:output});
try {
  const page=browser.contexts().flatMap(context=>context.pages()).find(page=>/^https?:\/\/localhost\//.test(page.url()));
  if(!page)throw new Error('No project WebView');
  await expect(page.locator('.ledger-app')).toBeVisible({timeout:30000});
  const read=async()=>page.evaluate(async()=>{const value=await window.Capacitor.nativePromise('LedgerStore','read',{});return value.snapshot;});
  const before=await read();
  const diagnostic=JSON.parse(fs.readFileSync(path.join(output,'large-read-diagnostic.json'),'utf8'));
  if(createHash('sha256').update(before.data).digest('hex')!==diagnostic.sha256)throw new Error('Large payload bytes changed during upgrade');
  const oldState=JSON.parse(before.data);
  if(oldState.transactions.length!==10000||oldState.schemaVersion!==1)throw new Error('Expected preserved v1 stress input');
  const active=()=>page.locator('.lj-route-frame:not([hidden])');
  await active().getByRole('button',{name:'数据与设置',exact:true}).click();
  await active().getByRole('button',{name:'夜间',exact:true}).click();
  await expect(page.locator('.ledger-app')).toHaveAttribute('data-theme','dark');
  const after=await read();const nextState=JSON.parse(after.data);
  if(nextState.schemaVersion!==2||nextState.transactions.length!==10000||after.revision!==before.revision+1)throw new Error('V2 durable commit failed');
  const fields=['id','bookId','direction','amountCents','date','time','accountId','categoryId','toAccountId','note','createdAt','updatedAt'];
  for(let index=0;index<10000;index++)for(const field of fields)if(nextState.transactions[index][field]!==oldState.transactions[index][field])throw new Error('Original transaction field changed: '+field);
  const unknown=new Set(nextState.members.filter(member=>member.kind==='unspecified').map(member=>member.id));
  if(!nextState.transactions.every(row=>unknown.has(row.memberId)))throw new Error('Missing historical member evidence was misassigned');
  await active().getByRole('button',{name:/历史保存点/}).click();
  const history=page.getByRole('dialog',{name:'历史保存点',exact:true});
  await expect(history).toBeVisible();
  await history.locator('.recovery-point').filter({hasText:'版本 '+before.revision}).getByRole('radio').check();
  await expect(history.getByText(/校验通过：10000 笔流水/)).toBeVisible({timeout:30000});
  await history.getByRole('button',{name:'取消',exact:true}).click();
  const final=await read();
  if(final.sha256!==after.sha256||final.revision!==after.revision)throw new Error('Cancelled recovery changed the ledger');
  await page.screenshot({path:path.join(output,'large-upgrade-history-verified.png'),fullPage:true});
  const report={transactions:10000,inputBytes:Buffer.byteLength(before.data),savedBytes:Buffer.byteLength(after.data),sourceSchema:1,savedSchema:2,revision:after.revision,originalFieldsPreserved:true,unknownMembersExplicit:true,historySelectionVerified:true,cancelDidNotWrite:true};
  fs.writeFileSync(path.join(output,'large-upgrade-verified.json'),JSON.stringify(report,null,2));
  console.log(JSON.stringify(report));
} finally {await browser.close();}

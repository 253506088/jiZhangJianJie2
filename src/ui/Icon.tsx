export function Icon({
  name,
  size = 21,
  className = '',
}: {
  name: string;
  size?: number;
  className?: string;
}) {
  const Component = icons[name as keyof typeof icons] ?? icons.category;
  return <Component size={size} strokeWidth={1.7} className={className} aria-hidden="true" />;
}


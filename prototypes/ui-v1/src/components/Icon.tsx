export function Icon({
  name,
  size = 22,
  className = '',
}: {
  name: string;
  size?: number;
  className?: string;
}) {
  const Component = icons[name as keyof typeof icons] ?? icons.more;
  return <Component size={size} strokeWidth={1.7} className={className} aria-hidden="true" />;
}
